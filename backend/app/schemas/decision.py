"""Pydantic V2 schemas for final verification decisions and multimodal score fusion."""

from __future__ import annotations

from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field

from app.schemas.pipeline import ContributingFactor, ScoreFusionOutput
from app.schemas.primitives import RiskBand


class VerificationVerdict(str, Enum):
    """Categorical verdict for certificate authenticity assessment."""

    AUTHENTIC = "AUTHENTIC"
    SUSPICIOUS = "SUSPICIOUS"
    MANIPULATED = "MANIPULATED"


class SubScoresBreakdown(BaseModel):
    """Normalized sub-scores across analytical branches [0.0 = Fake, 1.0 = Genuine]."""

    visual_branch_score: float = Field(..., ge=0.0, le=1.0, description="1.0 - P_visual_fake")
    tabular_branch_score: float = Field(..., ge=0.0, le=1.0, description="1.0 - P_tabular_fake")
    text_consistency_score: float = Field(..., ge=0.0, le=1.0, description="Rule-based consistency")
    forensic_score: float = Field(..., ge=0.0, le=1.0, description="Forensic integrity score")
    template_score: float = Field(..., ge=0.0, le=1.0, description="Template alignment score")


class FinalVerificationDecision(BaseModel):
    """Unified final decision DTO generated by multimodal score fusion."""

    certificate_id: str = Field(..., description="Unique certificate identifier")
    overall_authenticity_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Fused authenticity probability [0.0 = Fraud, 1.0 = Authentic]",
    )
    overall_risk_score: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Overall risk score [0.0 = Low Risk, 100.0 = High Risk]",
    )
    risk_band: RiskBand = Field(..., description="Risk category: LOW, MEDIUM, HIGH")
    verdict: VerificationVerdict = Field(..., description="Final verdict")
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Calibrated confidence level in verdict",
    )
    sub_scores: SubScoresBreakdown = Field(..., description="Branch sub-scores")
    tier_status: str = Field(default="TIER_3_UNVERIFIED", description="Tier from database records")
    veto_applied: bool = Field(default=False, description="True if institutional veto was applied")
    veto_reason: Optional[str] = Field(default=None, description="Explanation if veto was applied")
    contributing_factors: List[ContributingFactor] = Field(
        default_factory=list,
        description="Ranked list of factors influencing decision",
    )
    summary_rationale: str = Field(
        default="",
        description="Human-readable decision explanation for verifiers",
    )
    fusion_method: str = Field(
        default="stacking_meta_learner",
        description="Method used: stacking_meta_learner, late_fusion, or early_fusion_mlp",
    )
    latency_ms: float = Field(default=0.0, description="Decision execution latency in milliseconds")

    def to_score_fusion_output(self) -> ScoreFusionOutput:
        """Map to canonical SPEC-02 ScoreFusionOutput contract."""
        return ScoreFusionOutput(
            document_id=self.certificate_id,
            overall_risk_score=round(self.overall_risk_score, 2),
            risk_band=self.risk_band,
            confidence_level=round(self.confidence, 4),
            contributing_factors=self.contributing_factors,
        )
