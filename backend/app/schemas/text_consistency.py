import uuid
from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field

from app.schemas.pipeline import ConsistencyCheckItem, TextConsistencyOutput
from app.schemas.primitives import BoundingBox, CheckStatus, PixelBoundingBox


class AnomalyType(str, Enum):
    """Enumeration of detectable typographical and textual tampering anomalies."""

    BASELINE_DRIFT = "baseline_drift"
    FONT_SIZE_MISMATCH = "font_size_mismatch"
    STROKE_WEIGHT_DISCREPANCY = "stroke_weight_discrepancy"
    SPACING_IRREGULARITY = "spacing_irregularity"
    FORMAT_IRREGULARITY = "format_irregularity"
    LOGICAL_CONTRADICTION = "logical_contradiction"


class AnomalousRegion(BaseModel):
    """Pinpoints an anomalous text token or multi-token span flagged during inspection."""

    region_id: str = Field(default_factory=lambda: f"ano_{uuid.uuid4().hex[:8]}")
    anomaly_type: AnomalyType
    severity: float = Field(..., ge=0.0, le=1.0, description="Confidence/severity of anomaly")
    description: str = Field(
        ..., description="Human-readable explanation of why this region was flagged"
    )
    bbox: BoundingBox = Field(..., description="Normalized bounding coordinates [0.0, 1.0]")
    pixel_bbox: Optional[PixelBoundingBox] = Field(
        default=None, description="Absolute pixel bounding box"
    )
    token_text: Optional[str] = Field(default=None, description="Text content of the flagged token")


class TextConsistencyConfig(BaseModel):
    """Configuration thresholds for typographical and textual consistency checks."""

    # Baseline alignment parameters
    min_tokens_for_baseline: int = 3
    baseline_residual_px_threshold: float = 4.0
    baseline_sigma_multiplier: float = 2.5

    # Font size parameters
    font_size_ratio_upper: float = 1.35
    font_size_ratio_lower: float = 0.72
    font_size_tier_sigma_threshold: float = 2.5

    # Stroke width parameters
    stroke_width_ratio_threshold: float = 0.40
    max_stroke_width_px: int = 50

    # Spacing parameters
    micro_gap_ratio_threshold: float = 0.20
    macro_gap_ratio_threshold: float = 2.50
    line_leading_deviation_threshold: float = 0.40

    # Score weighting
    weight_baseline: float = 0.25
    weight_font_size: float = 0.20
    weight_stroke_weight: float = 0.20
    weight_spacing: float = 0.15
    weight_logical: float = 0.20

    # Visualization
    generate_overlay: bool = True


class TextConsistencyResult(BaseModel):
    """Detailed result DTO generated by TextConsistencyService."""

    document_id: str
    overall_text_consistency_score: float = Field(
        ..., ge=0.0, le=1.0, description="1.0 = completely consistent, 0.0 = highly anomalous"
    )
    baseline_alignment_score: float = Field(..., ge=0.0, le=1.0)
    font_size_consistency_score: float = Field(..., ge=0.0, le=1.0)
    stroke_weight_consistency_score: float = Field(..., ge=0.0, le=1.0)
    spacing_consistency_score: float = Field(..., ge=0.0, le=1.0)
    format_consistency_score: float = Field(..., ge=0.0, le=1.0)
    logical_consistency_score: float = Field(..., ge=0.0, le=1.0)

    anomalous_regions: List[AnomalousRegion] = Field(default_factory=list)
    checks: List[ConsistencyCheckItem] = Field(default_factory=list)
    visualization_image_path: Optional[str] = None
    execution_time_ms: float = 0.0

    @property
    def status(self) -> CheckStatus:
        """Derive overall check status from composite score."""
        if self.overall_text_consistency_score >= 0.85:
            return CheckStatus.PASSED
        elif self.overall_text_consistency_score >= 0.65:
            return CheckStatus.WARNING
        return CheckStatus.FAILED

    @property
    def consistency_risk_score(self) -> float:
        """Risk score on [0.0, 100.0] scale (0 = clean, 100 = completely forged)."""
        return round(
            float(max(0.0, min(100.0, (1.0 - self.overall_text_consistency_score) * 100.0))), 2
        )

    def to_pipeline_output(self) -> TextConsistencyOutput:
        """Convert to canonical SPEC-02 TextConsistencyOutput contract."""
        return TextConsistencyOutput(
            document_id=self.document_id,
            overall_status=self.status,
            consistency_risk_score=self.consistency_risk_score,
            checks=self.checks,
        )
